/**
 * Adapter converting CatalogueItem into the existing Product model
 * for full compatibility with EnquiryModal and Collection features
 */
export function catalogueItemToProduct(item: CatalogueItem): Product {
  const catMapping: Record<MainCatalogueFamilyId, Product['category']> = {
    'fabrics': 'fabrics',
    'denim-chambray': 'denim',
    'laces': 'laces',
    'accessories': 'accessories',
  };

  return {
    id: item.id,
    productCode: item.materialReference,
    name: item.name,
    category: catMapping[item.familyId] || 'fabrics',
    categoryLabel: item.familyLabel,
    subcategory: item.subcategory,
    description: item.description,
    shortDescription: item.description,
    fullDescription: item.description,
    images: [item.image],
    imageAlt: `Raw material sample of ${item.name}`,
    colours: item.colours || [],
    sizes: item.width ? [item.width] : item.variants || [],
    fabric: item.composition || '',
    price: 'Wholesale Quote on Request',
    availability: 'In Stock',
    active: true,
    patternType: 'woven-fabric',
    specifications: `${item.weave ? `Weave: ${item.weave}; ` : ''}${item.gsm ? `Weight: ${item.gsm}; ` : ''}${item.width ? `Width: ${item.width}` : ''}`,
    applications: item.applications || [],
    enquiryEnabled: true,
    width: item.width,
    gsm: item.gsm,
    weave: item.weave,
  };
}
